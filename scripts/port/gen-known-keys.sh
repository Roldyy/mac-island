#!/bin/bash
# Regenerates Sources/SettingsKit/VorssaintKnownKeys.swift from a pinned Vorssaint tree.
#
#   scripts/port/gen-known-keys.sh [<extracted-tree>] [<output-file>]
#
# Reads only Sources/Vorssaint/Core/Defaults.swift: the `DefaultsKey` enum (key names) and the
# `registeredDefaults` literal (the value type, when it is a plain literal). Never reads a user's
# preferences, never writes a value. Re-runnable: same tree, same output.
set -euo pipefail

root="$(cd "$(dirname "$0")/../.." && pwd)"
tree="${1:-/private/tmp/claude-501/vors/src/vorssaint-utils-3.4.2}"
out="${2:-$root/Sources/SettingsKit/VorssaintKnownKeys.swift}"
src="$tree/Sources/Vorssaint/Core/Defaults.swift"

[ -f "$src" ] || { echo "gen-known-keys: $src not found" >&2; exit 1; }

# One line per distinct key: "<key>\t<kind>" (kind: bool, int, double, string, array or any).
records="$(awk '
function kindOf(expr) {
    sub(/^[ \t]+/, "", expr); sub(/[ \t]*,[ \t]*(\/\/.*)?$/, "", expr); sub(/[ \t]*\/\/.*$/, "", expr)
    if (expr == "true" || expr == "false") return "bool"
    if (expr ~ /^-?[0-9]+$/) return "int"
    if (expr ~ /^-?[0-9]+\.[0-9]+$/) return "double"
    if (expr ~ /^"[^"]*"$/) return "string"
    if (expr ~ /^\[String\]\(\)$/) return "array"
    return "any"
}
/^enum DefaultsKey \{/ { inKeys = 1; next }
inKeys && /^\}/ { inKeys = 0 }
inKeys && /^    static let [A-Za-z0-9_]+ *= *"[^"]*"/ {
    line = $0
    sub(/^    static let /, "", line)
    name = line; sub(/ *=.*$/, "", name)
    val = line; sub(/^[^"]*"/, "", val); sub(/".*$/, "", val)
    keyOf[name] = val
    next
}
/static let registeredDefaults/ { inReg = 1; next }
inReg && /^    \]/ { inReg = 0 }
inReg && /^        DefaultsKey\.[A-Za-z0-9_]+:/ {
    line = $0
    sub(/^        DefaultsKey\./, "", line)
    name = line; sub(/:.*$/, "", name)
    expr = line; sub(/^[^:]*:/, "", expr)
    kindOfName[name] = kindOf(expr)
    next
}
END {
    for (n in keyOf) {
        k = (n in kindOfName) ? kindOfName[n] : "any"
        print keyOf[n] "\t" k
    }
}
' "$src" | LC_ALL=C sort -u)"

count="$(printf '%s\n' "$records" | awk -F'\t' '{print $1}' | LC_ALL=C sort -u | wc -l | tr -d ' ')"
typed="$(printf '%s\n' "$records" | awk -F'\t' '$2 != "any"' | wc -l | tr -d ' ')"

# A key whose constants disagree on the kind would show up twice.
dupes="$(printf '%s\n' "$records" | awk -F'\t' '{print $1}' | LC_ALL=C sort | uniq -d | head -3)"
[ -z "$dupes" ] || { echo "gen-known-keys: a key has two kinds: $dupes" >&2; exit 1; }

if [ -n "${EXPECTED_COUNT:-}" ] && [ "$count" != "$EXPECTED_COUNT" ]; then
    echo "gen-known-keys: expected $EXPECTED_COUNT keys, found $count" >&2
    exit 1
fi

{
    echo "// Generated by scripts/port/gen-known-keys.sh from Core/Defaults.swift of the pinned Vorssaint tree."
    echo "// Do not edit by hand: re-run the script. Key names and value kinds only, never a value."
    echo "// SPDX-License-Identifier: GPL-3.0-or-later"
    echo
    echo "/// Expected property-list type of a key, derived from its registered default when that is a plain literal."
    echo "public enum VorssaintValueKind: String, Sendable {"
    echo "    case bool, int, double, string, array"
    echo "}"
    echo
    echo "/// Every preference key Vorssaint 3.4.2 declares ($count names, $typed with a known value kind)."
    echo "public enum VorssaintKnownKeys {"
    echo "    public static let all: Set<String> = ["
    printf '%s\n' "$records" | awk -F'\t' '{ printf "        \"%s\",\n", $1 }'
    echo "    ]"
    echo
    echo "    /// Keys whose registered default is a plain literal. A key missing here has no checked type."
    echo "    public static let kinds: [String: VorssaintValueKind] = ["
    printf '%s\n' "$records" | awk -F'\t' '$2 != "any" { printf "        \"%s\": .%s,\n", $1, $2 }'
    echo "    ]"
    echo "}"
} > "$out"

echo "gen-known-keys: $count keys ($typed typed) -> $out" >&2
